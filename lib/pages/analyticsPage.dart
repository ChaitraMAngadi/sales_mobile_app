class _AnalyticsDetailModalState extends State<_AnalyticsDetailModal> {
  dynamic _data;
  bool _loading = true;
  bool _error = false;

  TimePeriod _period = TimePeriod.last7Days;
  DateTime? _customStart;
  DateTime? _customEnd;
  SelectableEntity _selectedEntity = SelectableEntity.all;

  // Holds the current validation error for the custom date range.
  // null => no error. Shown inline below the date inputs.
  String? _customDateError;

  late DateTime _appliedStart;
  late DateTime _appliedEnd;

  bool get _isRevenueByDoctor => widget.item.type == 'revenue-doctor';
  bool get _isRevenueByClinic => widget.item.type == 'revenue-clinic';
  bool get _hasEntitySelector => _isRevenueByDoctor || _isRevenueByClinic;

  @override
  void initState() {
    super.initState();
    final range = _rangeForPeriod(_period);
    _appliedStart = range.$1;
    _appliedEnd = range.$2;
    _load(_appliedStart, _appliedEnd);
  }

  (DateTime, DateTime) _rangeForPeriod(TimePeriod p) {
    final now = DateTime.now();
    final end = DateTime(now.year, now.month, now.day);
    switch (p) {
      case TimePeriod.last7Days:
        return (end.subtract(const Duration(days: 6)), end);
      case TimePeriod.last30Days:
        return (end.subtract(const Duration(days: 29)), end);
      case TimePeriod.last90Days:
        return (end.subtract(const Duration(days: 89)), end);
      case TimePeriod.last1Year:
        return (DateTime(end.year - 1, end.month, end.day), end);
      case TimePeriod.custom:
        return (_customStart ?? end, _customEnd ?? end);
    }
  }

  Map<String, String>? _entityParams() {
    if (!_hasEntitySelector) return null;
    final key = _isRevenueByDoctor ? 'doctorId' : 'hospitalId';
    final value = _selectedEntity.id.isEmpty ? 'all' : _selectedEntity.id;
    return {key: value};
  }

  Future<void> _load(DateTime start, DateTime end) async {
    setState(() {
      _loading = true;
      _error = false;
    });
    final res = await AnalyticsApi.fetch(
      widget.item.endpoint,
      startDate: start,
      endDate: end,
      extraParams: _entityParams(),
    );
    if (!mounted) return;
    setState(() {
      _loading = false;
      _appliedStart = start;
      _appliedEnd = end;
      if (res['success'] == true) {
        _data = res['data'];
      } else {
        _error = true;
      }
    });
  }

  // Validates the custom date range and either loads data or sets an
  // inline error message that's shown below the date pickers.
  Future<void> _onGetStatistics() async {
    if (_period == TimePeriod.custom) {
      if (_customStart == null || _customEnd == null) {
        setState(() {
          _customDateError = 'Please select both start and end date';
        });
        return;
      }
      if (_customStart!.isAfter(_customEnd!)) {
        setState(() {
          _customDateError = 'Start date must be before end date';
        });
        return;
      }
      setState(() => _customDateError = null);
      await _load(_customStart!, _customEnd!);
    } else {
      setState(() => _customDateError = null);
      final range = _rangeForPeriod(_period);
      await _load(range.$1, range.$2);
    }
  }

  Future<void> _pickCustomDate({required bool isStart}) async {
    final initial = isStart ? (_customStart ?? DateTime.now()) : (_customEnd ?? DateTime.now());
    final picked = await showDatePicker(
      context: context,
      initialDate: initial,
      firstDate: DateTime(2000),
      lastDate: DateTime(2100),
    );
    if (picked == null) return;
    setState(() {
      if (isStart) {
        _customStart = picked;
      } else {
        _customEnd = picked;
      }
      // Clear any previous validation error once the user picks a new date.
      _customDateError = null;
    });
  }

