  List<Widget> _renderData() {
    if (_data == null) return [const Text('No data')];

    dynamic data = _data;

    // Some revenue endpoints wrap the object in a List even for a single
    // doctor/clinic. Unwrap it so the card layout is used instead of
    // falling through to the raw key/value list.
    if (_hasEntitySelector && data is List) {
      if (data.isEmpty) return [const Text('No data')];
      data = data.first;
    }

    if (data is Map) {
      final map = (data as Map).map((k, v) => MapEntry(k.toString(), v));

      if (_hasEntitySelector) {
        return [_revenueLayout(map, widget.item.color)];
      }

      if (_isFlatScalarMap(map)) {
        map.removeWhere((k, _) =>
            k.toLowerCase().contains('startdate') || k.toLowerCase().contains('enddate'));
        return [_statCardsGrid(map, widget.item.color)];
      }
    }

    if (data is List) {
      final list = data as List;
      final widgets = <Widget>[];
      for (var i = 0; i < list.length; i++) {
        final row = list[i] as Map;
        widgets.add(Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: row.entries.map((e) => _field(e.key.toString(), e.value)).toList(),
        ));
        if (i < list.length - 1) widgets.add(const Divider(height: 24));
      }
      return widgets;
    }

    if (data is Map) {
      return (data as Map).entries.map((e) => _field(e.key.toString(), e.value)).toList();
    }

    return [Text(_renderValue(data))];
  }

  Widget _periodSelector() {
    final item = widget.item;
    return DropdownButtonFormField<TimePeriod>(
      value: _period,
      decoration: InputDecoration(
        contentPadding: const EdgeInsets.symmetric(horizontal: 14, vertical: 12),
        border: OutlineInputBorder(borderRadius: BorderRadius.circular(10), borderSide: BorderSide(color: item.color)),
        enabledBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(10), borderSide: BorderSide(color: item.color)),
        focusedBorder: OutlineInputBorder(
            borderRadius: BorderRadius.circular(10), borderSide: BorderSide(color: item.color, width: 1.5)),
      ),
      items: TimePeriod.values.map((p) => DropdownMenuItem(value: p, child: Text(p.label))).toList(),
      onChanged: (p) {
        if (p == null) return;
        setState(() {
          _period = p;
          // Switching away from / into custom clears any stale error.
          _customDateError = null;
        });
      },
    );
  }

