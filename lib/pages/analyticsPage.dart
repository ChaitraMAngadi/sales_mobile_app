// TIME PERIOD OPTIONS
// ─────────────────────────────────────────────────────────────────────────
enum TimePeriod { last7Days, last30Days, last90Days, last1Year, custom }

extension TimePeriodLabel on TimePeriod {
  String get label {
    switch (this) {
      case TimePeriod.last7Days:
        return 'Last 7 Days';
      case TimePeriod.last30Days:
        return 'Last 30 Days';
      case TimePeriod.last90Days:
        return 'Last 90 Days';
      case TimePeriod.last1Year:
        return 'Last 1 Year';
      case TimePeriod.custom:
        return 'Custom Range';
    }
  }
}

// ─────────────────────────────────────────────────────────────────────────
// SMALL DATE HELPERS (no intl dependency needed)
// ─────────────────────────────────────────────────────────────────────────
String _isoDate(DateTime d) =>
    '${d.year.toString().padLeft(4, '0')}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

const _monthNames = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December'
];

String _prettyDate(DateTime d) => '${_monthNames[d.month - 1]} ${d.day}, ${d.year}';

String _inputDate(DateTime? d) {
  if (d == null) return '';
  return '${d.day.toString().padLeft(2, '0')}-${d.month.toString().padLeft(2, '0')}-${d.year}';
}

