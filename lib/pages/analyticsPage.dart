class _AnalyticsDetailModal extends StatefulWidget {
  final AnalyticsCardData item;
  const _AnalyticsDetailModal({required this.item});

  static Future<void> show(BuildContext context, AnalyticsCardData item) {
    return showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (_) => _AnalyticsDetailModal(item: item),
    );
  }

  @override
  State<_AnalyticsDetailModal> createState() => _AnalyticsDetailModalState();
}

class _AnalyticsDetailModalState extends State<_AnalyticsDetailModal> {
  dynamic _data;
  bool _loading = true;
  bool _error = false;

  TimePeriod _period = TimePeriod.last7Days;
  DateTime? _customStart;
  DateTime? _customEnd;

  // The date range actually applied for the last fetch (shown in the banner).
  late DateTime _appliedStart;
  late DateTime _appliedEnd;

  @override
  void initState() {
    super.initState();
    final range = _rangeForPeriod(_period);
    _appliedStart = range.$1;
    _appliedEnd = range.$2;
    _load(_appliedStart, _appliedEnd);
  }

  (DateTime, DateTime) _rangeForPeriod(TimePeriod p) {
    final now = DateTime.now();
    final end = DateTime(now.year, now.month, now.day);
    switch (p) {
      case TimePeriod.last7Days:
        return (end.subtract(const Duration(days: 6)), end);
      case TimePeriod.last30Days:
        return (end.subtract(const Duration(days: 29)), end);
      case TimePeriod.last90Days:
        return (end.subtract(const Duration(days: 89)), end);
      case TimePeriod.last1Year:
        return (DateTime(end.year - 1, end.month, end.day), end);
      case TimePeriod.custom:
        return (_customStart ?? end, _customEnd ?? end);
    }
  }

  Future<void> _load(DateTime start, DateTime end) async {
    setState(() {
      _loading = true;
      _error = false;
    });
    final res = await AnalyticsApi.fetch(
      widget.item.endpoint,
      startDate: start,
      endDate: end,
    );
    if (!mounted) return;
    setState(() {
      _loading = false;
      _appliedStart = start;
      _appliedEnd = end;
      if (res['success'] == true) {
        _data = res['data'];
      } else {
        _error = true;
      }
    });
  }

  Future<void> _onGetStatistics() async {
    if (_period == TimePeriod.custom) {
      if (_customStart == null || _customEnd == null) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Please select both start and end date')),
        );
        return;
      }
      if (_customEnd!.isBefore(_customStart!)) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('End date cannot be before start date')),
        );
        return;
      }
      await _load(_customStart!, _customEnd!);
    } else {
      final range = _rangeForPeriod(_period);
      await _load(range.$1, range.$2);
    }
  }

  Future<void> _pickCustomDate({required bool isStart}) async {
    final initial = isStart ? (_customStart ?? DateTime.now()) : (_customEnd ?? DateTime.now());
    final picked = await showDatePicker(
      context: context,
      initialDate: initial,
      firstDate: DateTime(2000),
      lastDate: DateTime(2100),
    );
    if (picked == null) return;
    setState(() {
      if (isStart) {
        _customStart = picked;
      } else {
        _customEnd = picked;
      }
    });
  }

  // ── Generic value rendering for nested/complex data ──────────────────
  String _renderValue(dynamic val) {
    if (val == null) return '—';
    if (val is Map || val is List) {
      return const JsonEncoder.withIndent('  ').convert(val);
    }
    return val.toString();
  }

  Widget _field(String key, dynamic val) {
    return Container(
      padding: const EdgeInsets.symmetric(vertical: 8),
      decoration: const BoxDecoration(
        border: Border(bottom: BorderSide(color: Color(0xFFF3F4F6))),
      ),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          SizedBox(
            width: 130,
            child: Text(
              key.toUpperCase(),
              style: const TextStyle(fontSize: 11, fontWeight: FontWeight.w600, color: Colors.grey, letterSpacing: 0.5),
            ),
          ),
          Expanded(
            child: Text(_renderValue(val), style: const TextStyle(fontSize: 13, fontWeight: FontWeight.w500)),
          ),
        ],
      ),
    );
  }

  // camelCase key -> "Readable Label" (drops trailing "Count")
  String _labelFromKey(String key) {
    final spaced = key.replaceAllMapped(
      RegExp(r'([a-z0-9])([A-Z])'),
      (m) => '${m[1]} ${m[2]}',
    );
    final words = spaced
        .split(RegExp(r'[\s_]+'))
        .where((w) => w.isNotEmpty && w.toLowerCase() != 'count')
        .toList();
    if (words.isEmpty) return key;
    return words.map((w) => w[0].toUpperCase() + w.substring(1)).join(' ');
  }

  IconData _iconForKey(String key) {
    final k = key.toLowerCase();
    if (k.contains('active')) return Icons.person_outline;
    if (k.contains('created') || k.contains('total') || k.contains('doctor')) return Icons.groups_outlined;
    if (k.contains('revenue') || k.contains('amount') || k.contains('sales')) return Icons.currency_rupee;
    if (k.contains('clinic') || k.contains('hospital')) return Icons.local_hospital_outlined;
    return Icons.bar_chart_outlined;
  }

  String _subtitleForKey(String key) {
    final k = key.toLowerCase();
    if (k.contains('createddoctors')) return 'Total doctors registered';
    if (k.contains('activedoctors')) return 'Currently active doctors';
    return 'For the selected period';
  }

  bool _isFlatScalarMap(Map map) {
    return map.values.every((v) => v == null || v is num || v is String || v is bool);
  }

  // ── Stat card grid for flat Map<String, num/String> responses ────────
  Widget _statCardsGrid(Map<String, dynamic> map, Color accent) {
    final entries = map.entries.toList();
    return GridView.builder(
      shrinkWrap: true,
      physics: const NeverScrollableScrollPhysics(),
      itemCount: entries.length,
      gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
        crossAxisCount: 2,
        mainAxisSpacing: 14,
        crossAxisSpacing: 14,
        childAspectRatio: 1.15,
      ),
      itemBuilder: (context, i) {
        final entry = entries[i];
        return Container(
          padding: const EdgeInsets.all(16),
          decoration: BoxDecoration(
            color: accent.withOpacity(0.04),
            borderRadius: BorderRadius.circular(14),
            border: Border.all(color: accent.withOpacity(0.25)),
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Row(
                children: [
                  Icon(_iconForKey(entry.key), size: 16, color: accent),
                  const SizedBox(width: 6),
                  Expanded(
                    child: Text(
                      _labelFromKey(entry.key),
                      maxLines: 1,
                      overflow: TextOverflow.ellipsis,
                      style: TextStyle(fontSize: 12, fontWeight: FontWeight.w700, color: accent),
                    ),
                  ),
                ],
              ),
              const Spacer(),
              Text(
                _renderValue(entry.value),
                style: TextStyle(fontSize: 28, fontWeight: FontWeight.w800, color: accent),
              ),
              const SizedBox(height: 4),
              Text(
                _subtitleForKey(entry.key),
                style: const TextStyle(fontSize: 11, color: Colors.grey),
              ),
            ],
          ),
        );
      },
    );
  }

  List<Widget> _renderData() {
    if (_data == null) return [const Text('No data')];

    if (_data is Map && _isFlatScalarMap(_data as Map)) {
      final map = (_data as Map).map((k, v) => MapEntry(k.toString(), v));
      // Drop the date fields from the card grid; they're already in the banner.
      map.removeWhere((k, _) =>
          k.toLowerCase().contains('startdate') || k.toLowerCase().contains('enddate'));
      return [_statCardsGrid(map, widget.item.color)];
    }

    if (_data is List) {
      final list = _data as List;
      final widgets = <Widget>[];
      for (var i = 0; i < list.length; i++) {
        final row = list[i] as Map;
        widgets.add(Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: row.entries.map((e) => _field(e.key.toString(), e.value)).toList(),
        ));
        if (i < list.length - 1) widgets.add(const Divider(height: 24));
      }
      return widgets;
    }

    if (_data is Map) {
      return (_data as Map).entries.map((e) => _field(e.key.toString(), e.value)).toList();
    }

    return [Text(_renderValue(_data))];
  }

